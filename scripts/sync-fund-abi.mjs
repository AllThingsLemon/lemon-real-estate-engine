// Copies the real-estate-fund ABIs into src/fund/abi.ts, typed `as const` so
// viem checks every contract call. The fund repo is private and Cloudflare
// builds can't fetch it, so the ABIs live here, pinned to the commit they
// came from. Reads from a git ref, so the fund checkout can be on any branch.
//
//   pnpm sync:fund-abi ../real-estate-fund               origin/develop
//   pnpm sync:fund-abi ../real-estate-fund origin/main   another ref
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [repo, ref = 'origin/develop'] = process.argv.slice(2);
if (!repo) {
  console.error('usage: pnpm sync:fund-abi <path-to-real-estate-fund> [git-ref]');
  process.exit(1);
}

const git = (...args) => execFileSync('git', ['-C', resolve(repo), ...args], { encoding: 'utf8' });
const read = (name) => JSON.parse(git('show', `${ref}:contracts/abi/${name}.json`));

const commit = git('rev-parse', ref).trim();
const manifest = read('MANIFEST');
const sandbox = manifest.deployments?.bscTestnetSandbox ?? {};
const out = resolve(import.meta.dirname, '../src/fund/abi.ts');

const constant = (name, value) => `export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`;

writeFileSync(
  out,
  `// Generated by scripts/sync-fund-abi.mjs. Don't edit: run the script again.\n` +
    `// Source: AllThingsLemon/real-estate-fund ${ref} @ ${commit}\n\n` +
    constant('abiSource', { ref, commit, factoryVersion: sandbox.factoryVersion ?? null }) +
    '\n' +
    constant('projectAbi', read('Project')) +
    '\n' +
    constant('projectFactoryAbi', read('ProjectFactory')) +
    '\n' +
    constant('projectLensAbi', read('ProjectLens')) +
    '\n' +
    constant('deployments', manifest.deployments ?? {}),
);

console.log(`Wrote src/fund/abi.ts from ${ref} @ ${commit.slice(0, 7)} (factory version ${sandbox.factoryVersion ?? '?'})`);
